"""Makes the closing voice lines of the Dawn splash with Microsoft neural voices (via the edge-tts package).
结尾语音：用微软的神经网络语音（edge-tts）生成。设置页面里可以逐个试听、选择。

  pip install edge-tts
  python tools/make-voice.py                 # every voice listed in tools/voices.json
  python tools/make-voice.py --only ava      # just one of them
  python tools/make-voice.py --text "Welcome back, my dear friend."   # another line for all voices
  python tools/make-voice.py --list          # English female voices you could add to voices.json

For each voice it writes assets/voices/<id>.mp3 (to listen to) and assets/voices/<id>.js (what the splash loads),
plus assets/voices/index.js, the list the settings page shows.
The generated audio is not part of the repository (see .gitignore); everyone makes their own copy.
"""
import argparse, asyncio, base64, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRESETS = os.path.join(ROOT, 'tools', 'voices.json')
OUT = os.path.join(ROOT, 'assets', 'voices')


async def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', help='id from tools/voices.json')
    ap.add_argument('--text', help='the line to speak (default: the one in tools/voices.json)')
    ap.add_argument('--list', action='store_true')
    a = ap.parse_args()
    try:
        import edge_tts
    except ImportError:
        sys.exit('edge-tts is not installed: pip install edge-tts')
    if a.list:
        for v in await edge_tts.list_voices():
            if v['Locale'].startswith('en-') and v['Gender'] == 'Female':
                print(f"{v['ShortName']:34} {', '.join(v.get('VoiceTag', {}).get('VoicePersonalities', []))}")
        return
    with open(PRESETS, encoding='utf-8') as f:
        P = json.load(f)
    text = a.text or P['text']
    os.makedirs(OUT, exist_ok=True)
    made = []
    for v in P['voices']:
        if a.only and v['id'] != a.only:
            continue
        mp3 = os.path.join(OUT, v['id'] + '.mp3')
        await edge_tts.Communicate(text, v['voice'], rate=v['rate'], pitch=v['pitch']).save(mp3)
        with open(mp3, 'rb') as f:
            b64 = base64.b64encode(f.read()).decode('ascii')
        with open(os.path.join(OUT, v['id'] + '.js'), 'w', encoding='utf-8') as f:
            f.write(f"// Generated by tools/make-voice.py ({v['voice']}, rate {v['rate']}, pitch {v['pitch']})\n")
            f.write('window.SPLASH_VOICE_TEXT=' + json.dumps(text, ensure_ascii=False) + ';\n')
            f.write('window.SPLASH_VOICE="data:audio/mpeg;base64,' + b64 + '";\n')
        made.append(v['id'])
        print('wrote', mp3)
    # the list for the settings page: only voices whose files exist
    have = [dict(v, text=text) for v in P['voices'] if os.path.exists(os.path.join(OUT, v['id'] + '.js'))]
    with open(os.path.join(OUT, 'index.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/make-voice.py\n')
        f.write('window.DAWN_VOICES=' + json.dumps({'default': P['default'], 'voices': have}, ensure_ascii=False, indent=1) + ';\n')
    print(f'{len(made)} voice(s) made, {len(have)} in assets/voices/index.js')


asyncio.run(main())
